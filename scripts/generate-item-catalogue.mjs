// Regenerates src/lib/item-catalogue.ts from OpenDota's item constants, the
// same source OpenDota itself uses to name the item ids in a match payload.
// Run it when a patch adds items (an unknown id renders as "Item <id>"):
//
//   node scripts/generate-item-catalogue.mjs
//
// It only reads two public JSON files and writes one source file; review the
// diff before committing it.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const BASE = "https://api.opendota.com/api/constants";
const OUT = fileURLToPath(new URL("../src/lib/item-catalogue.ts", import.meta.url));

async function json(path) {
  const res = await fetch(`${BASE}/${path}`, { signal: AbortSignal.timeout(30_000) });
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  return res.json();
}

/** "caster_rapier" -> "Caster Rapier", for the few items OpenDota leaves unnamed. */
function titleCase(key) {
  return key
    .split("_")
    .filter(Boolean)
    .map((word) => word[0].toUpperCase() + word.slice(1))
    .join(" ");
}

function kindOf(key, item) {
  if (key.startsWith("recipe_")) return "recipe";
  if (key.startsWith("enhancement_")) return "enchantment";
  if (item.tier != null) return "neutral";
  if (typeof item.qual === "string" && item.qual.startsWith("consumable")) return "consumable";
  return "item";
}

const [items, ids] = await Promise.all([json("items"), json("item_ids")]);
const rows = [];
for (const [rawId, key] of Object.entries(ids)) {
  const id = Number(rawId);
  const item = items[key];
  if (!Number.isSafeInteger(id) || id <= 0 || !item) continue;
  // "/apps/dota2/images/dota_react/items/blink.png?t=..." -> "blink"
  const img = /\/items\/([a-z0-9_]+)\.png/.exec(item.img ?? "")?.[1];
  if (!img) continue;
  const name = typeof item.dname === "string" && item.dname.trim() ? item.dname.trim() : titleCase(key);
  rows.push({ id, img, name, kind: kindOf(key, item) });
}
rows.sort((a, b) => a.id - b.id);

const lines = rows.map(
  (row) => `  { id: ${row.id}, img: ${JSON.stringify(row.img)}, name: ${JSON.stringify(row.name)}, kind: "${row.kind}" },`,
);
writeFileSync(
  OUT,
  `// Generated by scripts/generate-item-catalogue.mjs from OpenDota
// /constants/items and /constants/item_ids. Do not edit by hand: rerun the
// script when a patch adds items. Kept in-repo, like the hero table, so no
// item label depends on OpenDota being up.

import type { Item } from "./items";

export const ITEMS: readonly Item[] = [
${lines.join("\n")}
];
`,
);
console.log(`Wrote ${rows.length} items to ${OUT}`);
